// Generates the guest program of the QuickJS engine for the `javascript` option on edge runtimes:
//
//   dist/edge-js-payload.js  the guest program as QuickJS bytecode (base64): shims, the Web Streams polyfill, the boot code
//                            and the native DOM layer. `src/index.ts` runs it in QuickJS.
//
// Needs dist/quickjs.wasm (scripts/build-quickjs.mjs) and dist/runtime.js (tsc).
// Usage (from `packages/quickjs-dom/`): node scripts/build-edge-js.mjs
import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { createRequire } from "node:module";
import { dirname, join } from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const root = join(here, "..");
const require = createRequire(join(root, "package.json"));
const read = (path) => readFileSync(path, "utf8");

// The guest has no DOM library: the DOM is csrc/nativedom*.h with scripts/edge-js/nativedom.js on top.

const streamsPath = join(dirname(require.resolve("web-streams-polyfill/package.json")), "dist", "polyfill.js");
const domParts = [
  "01-core.js",
  "02-classes.js",
  "03-interaction.js",
  "04-xpath.js",
  "05-html.js",
].map((file) => read(join(here, "edge-js", "dom", file)));

const parts = [
  read(join(here, "edge-js", "shims.js")),
  read(streamsPath),
  ...domParts,
  read(join(here, "edge-js", "computed.js")),
  read(join(here, "edge-js", "boot.js")),
  read(join(here, "edge-js", "rpc.js")),
];
const source = parts.join("\n;\n");

mkdirSync(join(root, "dist"), { recursive: true });

// The guest program is shipped as QuickJS bytecode, which the QuickJS of dist/quickjs.wasm reads in about a millisecond
// where compiling the source takes tens (and which is smaller than the source). It only runs on that very build, so
// it is made here, with that wasm (build-quickjs.mjs runs first, tsc has made dist/runtime.js).
const { QuickJSInstance } = await import(pathToFileURL(join(root, "dist", "runtime.js")).href);
const wasm = new WebAssembly.Module(readFileSync(join(root, "dist", "quickjs.wasm")));
const host = { log() {}, timer() {}, rejection() {}, fetch() {}, module: () => undefined };
const bytes = QuickJSInstance.create(wasm, host, 256 * 1024 * 1024, 192 * 1024).compile(source, "edge-js-guest.js");
const check = QuickJSInstance.create(wasm, host, 256 * 1024 * 1024, 192 * 1024).evalBytecode(bytes);
if (check.type === "error") throw new Error("build-edge-js: the bytecode does not run: " + check.value);
writeFileSync(
  join(root, "dist", "edge-js-payload.js"),
  `// generated by scripts/build-edge-js.mjs; do not edit
export const guestBytecode = ${JSON.stringify(Buffer.from(bytes).toString("base64"))};
`,
);
console.log(`edge-js: source ${(source.length / 1024).toFixed(0)} KiB -> bytecode ${(bytes.length / 1024).toFixed(0)} KiB`);
