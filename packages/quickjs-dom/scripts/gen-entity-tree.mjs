// Regenerates csrc/entity_tree.h: the HTML named-entity trie of the `entities` package (the one htmlparser2 decodes
// with), as a C array. csrc/htmlparse.h walks it exactly like entities' EntityDecoder does.
//
// Usage (from `packages/quickjs-dom/`): node scripts/gen-entity-tree.mjs
// The header is committed: building the wasm does not need this script or node_modules.
import { realpathSync, writeFileSync } from "node:fs";
import { createRequire } from "node:module";
import { dirname, join } from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const require = createRequire(import.meta.url);
const htmlparser2 = realpathSync(dirname(require.resolve("htmlparser2/package.json")));
const entities = realpathSync(join(htmlparser2, "..", "entities"));
const version = JSON.parse((await import("node:fs")).readFileSync(join(entities, "package.json"), "utf8")).version;
const { htmlDecodeTree } = await import(pathToFileURL(join(entities, "dist", "esm", "generated", "decode-data-html.js")).href);

const lines = [];
for (let i = 0; i < htmlDecodeTree.length; i += 16) lines.push("  " + Array.from(htmlDecodeTree.subarray(i, i + 16)).join(",") + ",");
writeFileSync(
  join(root, "csrc", "entity_tree.h"),
  `/* Generated by scripts/gen-entity-tree.mjs from entities@${version} (BSD-2-Clause, see THIRD-PARTY-NOTICES.md). Do not edit. */\n` +
    `#define ENTITY_TREE_LEN ${htmlDecodeTree.length}\n` +
    `static const uint16_t entity_tree[ENTITY_TREE_LEN] = {\n${lines.join("\n")}\n};\n`,
);
console.log(`entity_tree.h: ${htmlDecodeTree.length} entries (entities@${version})`);
