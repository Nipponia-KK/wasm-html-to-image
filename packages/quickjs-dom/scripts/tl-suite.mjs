// @testing-library/dom's own test suite, run twice: once under its own jsdom environment (the
// baseline) and once with the environment swapped for this package's jest environment. The
// library's tests are not in its npm package, so the matching tag of the repository is cloned
// into node_modules/.cache (a one-time download) and installed there.
//
//   node scripts/tl-suite.mjs [--deny-skips] [--dual-run] [--runs=N]
//                             [--expect-baseline=N] [--expect-ours=N] [--total=N]
//
// The result is checked, not just measured: the counts must match the ledger (tests/known-gaps.json
// -> tlSuite), every failure that happens only under ours must be registered there, and --deny-skips
// refuses pending/skipped/todo/disabled tests. --dual-run (--runs=2) runs each environment twice and
// requires the same failing set, so a flaky failure cannot pass as "accepted".
import { execFileSync, spawnSync } from "node:child_process";
import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { createRequire } from "node:module";
import path from "node:path";
import { fileURLToPath } from "node:url";

const here = path.dirname(fileURLToPath(import.meta.url));
const root = path.join(here, "..");
const require = createRequire(path.join(root, "package.json"));
const version = require("@testing-library/dom/package.json").version;
const dir = path.join(root, "node_modules", ".cache", "tl-dom-suite");

const argv = process.argv.slice(2);
const flag = (name) => argv.includes(name);
const option = (name, fallback) => {
  for (let i = 0; i < argv.length; i++) {
    const a = argv[i];
    if (a === name) return argv[i + 1] !== undefined && !argv[i + 1].startsWith("--") ? argv[i + 1] : true;
    if (a.startsWith(`${name}=`)) return a.slice(name.length + 1);
  }
  return fallback;
};
const usage = `Usage: node scripts/tl-suite.mjs [options]

  --deny-skips            fail if any test is pending / skipped / todo / disabled
  --dual-run              run each environment twice (same as --runs=2); the failing sets must match
  --runs=N                number of runs per environment (default 1)
  --expect-baseline=N     expected passing tests under jsdom (default: tlSuite.baseline in the ledger)
  --expect-ours=N         expected passing tests under this package (default: tlSuite.ours)
  --total=N               expected total tests (default: tlSuite.total)
  --keep                  keep the cloned suite (the directory is reused anyway)
  --help                  print this help and exit
`;
if (flag("--help") || flag("-h")) {
  console.log(usage);
  process.exit(0);
}

const ledger = JSON.parse(readFileSync(path.join(root, "tests", "known-gaps.json"), "utf8"));
const tl = ledger.tlSuite ?? {};
const expectBaseline = Number(option("--expect-baseline", tl.baseline ?? 657));
const expectOurs = Number(option("--expect-ours", tl.ours ?? 654));
const expectTotal = Number(option("--total", tl.total ?? 657));
const runs = flag("--dual-run") ? Math.max(2, Number(option("--runs", 2))) : Number(option("--runs", 1));
const denySkips = flag("--deny-skips");
const problems = [];

if (!Number.isInteger(runs) || runs < 1) problems.push(`--runs must be a positive integer (got ${option("--runs", "")})`);
for (const [name, value] of [["--expect-baseline", expectBaseline], ["--expect-ours", expectOurs], ["--total", expectTotal]]) {
  if (!Number.isInteger(value) || value < 1) problems.push(`${name} must be a positive integer (got ${value})`);
}
if (tl.version && tl.version !== version) problems.push(`ledger tlSuite.version is ${tl.version}, installed @testing-library/dom is ${version}: re-triage before trusting the counts`);
if (problems.length) {
  console.error("tl-suite: cannot run");
  for (const p of problems) console.error(`  - ${p}`);
  process.exit(1);
}

const run = (cmd, args, cwd) => {
  // npx/npm are .cmd shims on Windows: spawnSync only finds them through the shell
  const r = spawnSync(cmd, args, { cwd, stdio: "inherit", shell: process.platform === "win32" });
  if (r.status !== 0 && cmd !== "npx") throw new Error(`${cmd} ${args.join(" ")} failed`);
  return r.status;
};

if (!existsSync(path.join(dir, "package.json"))) {
  console.log(`cloning dom-testing-library v${version} into ${dir}`);
  execFileSync("git", ["clone", "--depth", "1", "--branch", `v${version}`, "https://github.com/testing-library/dom-testing-library.git", dir], { stdio: "inherit" });
}
if (!existsSync(path.join(dir, "node_modules"))) {
  console.log("installing the suite's own dependencies");
  execFileSync("npm", ["install", "--no-audit", "--no-fund", "--loglevel=error"], { cwd: dir, stdio: "inherit" });
}
writeFileSync(
  path.join(dir, "tests", "jest.config.ours.js"),
  `// generated by scripts/tl-suite.mjs: the library's dom project with the environment swapped\nconst base = require('./jest.config.dom')\nmodule.exports = { ...base, displayName: 'ours', testEnvironment: ${JSON.stringify(path.join(root, "jest.cjs"))} }\n`,
);

const out = (name, i) => path.join(dir, `${name}-${i}.json`);
const read = (name, i) => JSON.parse(readFileSync(out(name, i), "utf8"));
const failing = (d) => {
  const set = new Set();
  for (const suite of d.testResults) for (const a of suite.assertionResults) if (a.status === "failed") set.add(`${path.basename(suite.name)} :: ${a.title}`);
  return set;
};
const skipped = (d) => {
  const set = new Set();
  for (const suite of d.testResults) for (const a of suite.assertionResults) if (["pending", "skipped", "todo", "disabled"].includes(a.status)) set.add(`${path.basename(suite.name)} :: ${a.title} (${a.status})`);
  return set;
};
const diff = (a, b) => [...a].filter((x) => !b.has(x));

const results = { baseline: [], ours: [] };
for (let i = 0; i < runs; i++) {
  for (const [name, config] of [["baseline", "tests/jest.config.dom.js"], ["ours", "tests/jest.config.ours.js"]]) {
    run("npx", ["jest", "--config", config, "--ci", "--json", "--outputFile", out(name, i)], dir);
    results[name].push(read(name, i));
  }
}

// 1. dual-run: the same environment must produce the same failing set every time
for (const name of ["baseline", "ours"]) {
  const first = failing(results[name][0]);
  for (let i = 1; i < runs; i++) {
    const changed = [...diff(first, failing(results[name][i])), ...diff(failing(results[name][i]), first)];
    if (changed.length) problems.push(`${name} run 1 vs run ${i + 1}: failing set differs (${changed.join("; ")})`);
  }
}

// 2. counts: the ledger's acceptance line
for (const name of ["baseline", "ours"]) {
  const expected = name === "baseline" ? expectBaseline : expectOurs;
  for (let i = 0; i < runs; i++) {
    const d = results[name][i];
    if (d.numPassedTests !== expected) problems.push(`${name} run ${i + 1}: ${d.numPassedTests} passed, expected ${expected}`);
    if (d.numTotalTests !== expectTotal) problems.push(`${name} run ${i + 1}: ${d.numTotalTests} total, expected ${expectTotal}`);
  }
}

// 3. skips: --deny-skips, and never silently accept a skip as a pass
for (const name of ["baseline", "ours"]) {
  for (let i = 0; i < runs; i++) {
    const s = skipped(results[name][i]);
    if (s.size) {
      const list = [...s].join("; ");
      if (denySkips) problems.push(`${name} run ${i + 1}: ${s.size} skipped/pending test(s): ${list}`);
      else console.log(`\n${name} run ${i + 1}: ${s.size} skipped/pending test(s) (use --deny-skips to fail): ${list}`);
    }
  }
}

// 4. only-ours failures must be registered in the ledger
const base = results.baseline[0], ours = results.ours[0];
console.log(`\nbaseline (jsdom): ${base.numPassedTests}/${base.numTotalTests}`);
console.log(`ours:             ${ours.numPassedTests}/${ours.numTotalTests}${runs > 1 ? ` (x${runs} runs)` : ""}`);
const onlyOurs = [...failing(ours)].filter((t) => !failing(base).has(t));
console.log(onlyOurs.length ? `\nfailing only under ours (${onlyOurs.length}):` : "\nnothing fails only under ours");
for (const t of onlyOurs) console.log(`  - ${t}`);

const accepted = Array.isArray(tl.accepted) ? tl.accepted : [];
const matcher = (spec) => {
  if (typeof spec !== "string") return null;
  if (spec.startsWith("/") && spec.lastIndexOf("/") > 0) return new RegExp(spec.slice(1, spec.lastIndexOf("/")), spec.slice(spec.lastIndexOf("/") + 1));
  return new RegExp(spec.replace(/[.*+?^${}()|[\]\\]/g, "\\$&"), "i");
};
const registeredBy = (key) => accepted.find((e) => { const re = matcher(e.match); return re && re.test(key); });
const unregistered = onlyOurs.filter((t) => !registeredBy(t));
if (unregistered.length) {
  for (const t of unregistered) problems.push(`only-ours failure is not registered in tests/known-gaps.json tlSuite.accepted: ${t}`);
} else if (onlyOurs.length) {
  console.log("\nall only-ours failures are registered in tests/known-gaps.json tlSuite.accepted");
}
const unused = accepted.filter((e) => { const re = matcher(e.match); return re && !onlyOurs.some((t) => re.test(t)); });
if (unused.length) console.log(`note: ${unused.length} tlSuite.accepted entr${unused.length === 1 ? "y matches" : "ies match"} nothing this run: ${unused.map((e) => e.id).join(", ")}`);

if (problems.length) {
  console.error(`\ntl-suite: ${problems.length} problem(s)`);
  for (const p of problems) console.error(`  - ${p}`);
  process.exitCode = 1;
} else {
  console.log("\ntl-suite: PASS");
}
